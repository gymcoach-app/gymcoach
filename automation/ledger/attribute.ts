import { createHash } from 'node:crypto';
import type { PricedTokens } from '@/automation/usage/prices';
import type { RunTarget, SessionSummary } from '@/automation/usage/build';
import type { AgentLine, LedgerLine, ModelGroup, SessionLine } from '@/automation/ledger/schema';

// Pure: run-time ledger lines in, the session summaries that
// automation/usage/build.ts (buildUsageRecords) already turns into per-run
// usage records. So the ledger feeds the same usage.jsonl shape as the
// transcript scan of #443, with the same attribution rules (head branch, or a
// single PR reference) and the same "unknown, never 0" rule.

// Same 16-hex SHA-256 prefix as the hook (record-usage.cjs hash()).
export function hash16(value: string): string {
  return createHash('sha256').update(value).digest('hex').slice(0, 16);
}

// The ledger holds hashed branch names; the run's head branch is hashed the
// same way, so the head-branch rule still compares like with like.
export function hashRunBranches(runs: RunTarget[]): RunTarget[] {
  return runs.map((r) => ({
    ...r,
    headBranch: r.headBranch === null ? null : hash16(r.headBranch),
  }));
}

const asCount = (v: number | null): number => (v === null ? Number.NaN : v);

// A ledger line keeps sums per (model, speed). buildUsageRecords counts and
// prices responses, so each group becomes `responses` pseudo-responses: the
// first carries the group's sums, the others carry zero tokens. Token totals,
// response counts and the estimated cost (linear in tokens, priced per model
// and speed) are therefore the same as from the original responses.
function pseudoResponses(prefix: string, groups: ModelGroup[]): Map<string, PricedTokens> {
  const out = new Map<string, PricedTokens>();
  groups.forEach((g, gi) => {
    for (let i = 0; i < g.responses; i += 1) {
      const first = i === 0;
      const zeroOr = (v: number | null) => (first ? asCount(v) : v === null ? Number.NaN : 0);
      out.set(`${prefix}#${gi}.${i}`, {
        model: g.model,
        speed: g.speed,
        input: zeroOr(g.input),
        output: zeroOr(g.output),
        cacheRead: zeroOr(g.cacheRead),
        cacheCreation5m: zeroOr(g.cacheCreation5m),
        cacheCreation1h: zeroOr(g.cacheCreation1h),
      });
    }
  });
  return out;
}

export interface LedgerSessions {
  sessions: SessionSummary[];
  // Agent lines whose fork parent could not be read: their copied turn may
  // also be counted in the parent's session line.
  forksWithUncheckedParent: number;
  // Lines superseded by a later line for the same agent or session (a resumed
  // agent or session is summarised again, in full, when it stops again).
  superseded: number;
}

// The latest line per agent id and per session key wins: each line summarises
// the whole transcript at that moment.
function latest<T extends { at: string }>(lines: T[], key: (l: T) => string): T[] {
  const byKey = new Map<string, T>();
  for (const l of lines) {
    const k = key(l);
    const prev = byKey.get(k);
    if (!prev || l.at >= prev.at) byKey.set(k, l);
  }
  return [...byKey.values()];
}

function agentSession(l: AgentLine): SessionSummary {
  return {
    id: `agent:${l.agentId}`,
    kind: 'subagent',
    responses: pseudoResponses(`agent:${l.agentId}`, l.byModel),
    firstAt: l.firstAt,
    lastAt: l.lastAt,
    branches: new Set(l.branchHashes),
    pullRefs: new Set(l.pullRefs),
    prRefs: new Set(l.prRefs),
    skills: new Set(l.skills),
    prLinks: new Set(),
    droppedResponses: l.droppedResponses,
  };
}

function mainSession(l: SessionLine): SessionSummary {
  return {
    id: `session:${l.sessionKey}`,
    kind: 'main',
    responses: pseudoResponses(`session:${l.sessionKey}`, l.byModel),
    firstAt: l.firstAt,
    lastAt: l.lastAt,
    branches: new Set(),
    pullRefs: new Set(),
    prRefs: new Set(),
    skills: new Set(l.skills),
    prLinks: new Set(l.prLinks),
    droppedResponses: l.droppedResponses,
  };
}

export function ledgerToSessions(lines: LedgerLine[]): LedgerSessions {
  const agents = lines.filter((l): l is AgentLine => l.kind === 'agent');
  const mains = lines.filter((l): l is SessionLine => l.kind === 'session');
  const keptAgents = latest(agents, (l) => l.agentId);
  const keptMains = latest(mains, (l) => l.sessionKey);
  return {
    sessions: [...keptMains.map(mainSession), ...keptAgents.map(agentSession)],
    forksWithUncheckedParent: keptAgents.filter((l) => l.inheritedResponses === null).length,
    superseded: agents.length - keptAgents.length + mains.length - keptMains.length,
  };
}

export interface PromptCounts {
  // Main sessions with at least one recorded prompt.
  sessions: number;
  // Prompts not generated by the harness: the operator's, or a scripted
  // `claude -p` prompt. Not attributable to a run: a session spans many.
  other: number;
  // Harness notifications (a background task finished).
  notifications: number;
}

export function countPrompts(lines: LedgerLine[]): PromptCounts {
  const prompts = lines.filter((l) => l.kind === 'prompt');
  return {
    sessions: new Set(prompts.map((p) => p.sessionKey)).size,
    other: prompts.filter((p) => p.kind === 'prompt' && p.source === 'other').length,
    notifications: prompts.filter((p) => p.kind === 'prompt' && p.source === 'notification').length,
  };
}

// Ledger lines that do not parse are counted, not fatal.
export function parseLedger(
  text: string,
  parse: (raw: unknown) => LedgerLine,
): { lines: LedgerLine[]; invalid: number } {
  const lines: LedgerLine[] = [];
  let invalid = 0;
  for (const raw of text.split('\n')) {
    if (!raw.trim()) continue;
    try {
      lines.push(parse(JSON.parse(raw)));
    } catch {
      invalid += 1;
    }
  }
  return { lines, invalid };
}
