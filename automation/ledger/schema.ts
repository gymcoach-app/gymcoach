import { z } from 'zod';

// Lines of the run-time usage ledger written by automation/hooks/record-usage.cjs
// and, for green-gate runs, automation/ledger/record-verify.cjs (roadmap
// milestone 1). The ledger lives outside the repository; these lines hold
// numbers, model ids, skill names, public PR numbers, random agent ids, commit
// and tree SHAs and SHA-256 prefixes of session ids and branch names, never
// text or paths.

export const LEDGER_VERSION = 1 as const;

const isoDate = z.string().datetime();
const hash16 = z.string().regex(/^[0-9a-f]{16}$/);
// null: a response did not record this count, so the sum is unknown.
const tokenSum = z.number().int().nonnegative().nullable();

const modelGroupSchema = z
  .object({
    model: z.string().regex(/^(claude-[a-z0-9.-]+|other)$/),
    speed: z.string().nullable(),
    responses: z.number().int().positive(),
    input: tokenSum,
    output: tokenSum,
    cacheRead: tokenSum,
    cacheCreation5m: tokenSum,
    cacheCreation1h: tokenSum,
  })
  .strict();
export type ModelGroup = z.infer<typeof modelGroupSchema>;

const usageFields = {
  claudeVersion: z.string().nullable(),
  firstAt: isoDate.nullable(),
  lastAt: isoDate.nullable(),
  responses: z.number().int().nonnegative(),
  droppedResponses: z.number().int().nonnegative(),
  byModel: z.array(modelGroupSchema),
  skills: z.array(z.string().regex(/^[a-z0-9][a-z0-9:-]*$/)),
};

const prNumbers = z.array(z.number().int().positive());

export const agentLineSchema = z
  .object({
    v: z.literal(LEDGER_VERSION),
    kind: z.literal('agent'),
    at: isoDate,
    sessionKey: hash16,
    agentId: z.string().min(1).max(64),
    agentType: z.string().nullable(),
    // Hashes of the non-default branches the agent worked on from inside an
    // agent worktree.
    branchHashes: z.array(hash16),
    pullRefs: prNumbers,
    prRefs: prNumbers,
    // Responses copied from the parent's turn (forks), left out; null when the
    // parent transcript could not be read.
    inheritedResponses: z.number().int().nonnegative().nullable(),
    ...usageFields,
  })
  .strict();

export const sessionLineSchema = z
  .object({
    v: z.literal(LEDGER_VERSION),
    kind: z.literal('session'),
    at: isoDate,
    sessionKey: hash16,
    prLinks: prNumbers,
    ...usageFields,
  })
  .strict();

export const promptLineSchema = z
  .object({
    v: z.literal(LEDGER_VERSION),
    kind: z.literal('prompt'),
    at: isoDate,
    sessionKey: hash16,
    // "notification": generated by the harness (a background task finished);
    // "other": anything else, the operator's prompt or a scripted one.
    source: z.enum(['notification', 'other']),
  })
  .strict();

// One green-gate run, written by automation/ledger/record-verify.cjs from
// scripts/verify.sh's exit handler (not by the usage hook). treeSha is the
// tree of the files the gate checked: HEAD's tree on a clean checkout, else
// the tree a commit of the working files would have. It is taken before the
// first step and at exit and kept only when both agree; otherwise treeSha is
// null and treeChanged true (null when either tree could not be read). exit
// is null when the shell died from a signal during a step.
export const verifyStepNames = [
  'slot',
  'prisma',
  'lint',
  'typecheck',
  'unit',
  'script-tests',
  'build',
  'infra-lock',
  'test-db',
  'integration',
  'e2e',
] as const;
const sha40 = z.string().regex(/^[0-9a-f]{40}$/);

export const verifyLineSchema = z
  .object({
    v: z.literal(LEDGER_VERSION),
    kind: z.literal('verify'),
    at: isoDate,
    startedAt: isoDate.nullable(),
    // The Claude Code session the gate ran in (same hash as the usage hook's
    // sessionKey); null outside Claude Code.
    sessionKey: hash16.nullable(),
    inClaudeCode: z.boolean(),
    tier: z.enum(['default', 'full']),
    exit: z.number().int().min(0).max(255).nullable(),
    steps: z.array(
      z
        .object({
          name: z.enum(verifyStepNames),
          outcome: z.enum(['passed', 'failed', 'interrupted']),
          ms: z.number().int().nonnegative(),
        })
        .strict(),
    ),
    headSha: sha40.nullable(),
    treeSha: sha40.nullable(),
    // Absent on lines written before the start-and-exit comparison existed.
    treeChanged: z.boolean().nullable().optional(),
    dirty: z.boolean().nullable(),
    branchHash: hash16.nullable(),
  })
  .strict();

export const ledgerLineSchema = z.discriminatedUnion('kind', [
  agentLineSchema,
  sessionLineSchema,
  promptLineSchema,
  verifyLineSchema,
]);
export type AgentLine = z.infer<typeof agentLineSchema>;
export type SessionLine = z.infer<typeof sessionLineSchema>;
export type PromptLine = z.infer<typeof promptLineSchema>;
export type VerifyLine = z.infer<typeof verifyLineSchema>;
export type LedgerLine = z.infer<typeof ledgerLineSchema>;
